import { describeFilter, type UnitFilter } from "@/lib/org-units";

export type Eea13Row = {
  level: string;
  n: number;
  desigPct: number;
  femPct: number;
  target: { males: number; females: number; total: number };
  hires: number;
};

export type Eea13PdfInput = {
  planTitle: string;
  sector: string;
  startDate: string | null;
  endDate: string | null;
  filter: UnitFilter;
  workforceDate: string | undefined;
  rows: Eea13Row[];
  years: string[];
  gaps: string[];
};

const NAVY: [number, number, number] = [15, 34, 64];
const TEAL: [number, number, number] = [13, 148, 136];
const GREY: [number, number, number] = [90, 100, 112];

export async function exportEea13Pdf(input: Eea13PdfInput) {
  const { jsPDF } = await import("jspdf");
  const autoTable = (await import("jspdf-autotable")).default;
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const W = 210;

  doc.setFillColor(...NAVY);
  doc.rect(0, 0, W, 30, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(15);
  doc.setFont("helvetica", "bold");
  doc.text("EEA13 Numerical Goals & Targets", 14, 13);
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.text("DDHS Equity Intelligence — Employment Equity plan reporting", 14, 20);
  doc.setTextColor(...TEAL);
  doc.text(new Date().toLocaleDateString("en-ZA", { day: "numeric", month: "long", year: "numeric" }), W - 14, 13, { align: "right" });

  let y = 40;
  doc.setTextColor(...GREY);
  doc.setFontSize(9);
  doc.text("Plan", 14, y);
  doc.text("Sector", 90, y);
  doc.text("Period", 150, y);
  doc.setTextColor(20, 20, 20);
  doc.setFontSize(10);
  doc.text(doc.splitTextToSize(input.planTitle, 70), 14, y + 5);
  doc.text(doc.splitTextToSize(input.sector || "—", 55), 90, y + 5);
  doc.text(`${input.startDate ?? "—"} to ${input.endDate ?? "—"}`, 150, y + 5);
  y += 14;
  doc.setTextColor(...GREY);
  doc.setFontSize(9);
  doc.text(`Scope: ${describeFilter(input.filter)}   ·   Headcount: Workforce Data ${input.workforceDate ?? "—"}`, 14, y);

  y += 8;
  doc.setTextColor(...NAVY);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Goals and targets per occupational level", 14, y);
  doc.setFont("helvetica", "normal");

  autoTable(doc, {
    startY: y + 3,
    head: [["Level", "Headcount", "Designated now", "Women now", "Target des. males %", "Target women %", "Target designated %", "Appointments needed"]],
    body: input.rows.map((r) => [
      r.level,
      String(r.n),
      `${r.desigPct.toFixed(1)}%`,
      `${r.femPct.toFixed(1)}%`,
      r.target.males.toFixed(1),
      r.target.females.toFixed(1),
      r.target.total.toFixed(1),
      String(r.hires),
    ]),
    theme: "striped",
    headStyles: { fillColor: NAVY, fontSize: 7.5 },
    styles: { fontSize: 8 },
    margin: { left: 14, right: 14 },
  });

  // @ts-expect-error jspdf-autotable adds lastAutoTable
  y = (doc.lastAutoTable?.finalY ?? y + 40) + 10;
  doc.setTextColor(...NAVY);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Yearly timeline — designated groups %", 14, y);
  doc.setFont("helvetica", "normal");

  autoTable(doc, {
    startY: y + 3,
    head: [["Level", "Now", ...input.years.map((d, i) => `Year ${i + 1} (${d.slice(0, 4)})`)]],
    body: input.rows.map((r) => {
      const b = r.desigPct;
      return [r.level, b.toFixed(1), ...input.years.map((_, i) => Math.max(b, b + ((r.target.total - b) * (i + 1)) / input.years.length).toFixed(1))];
    }),
    theme: "striped",
    headStyles: { fillColor: TEAL, fontSize: 8 },
    styles: { fontSize: 8 },
    margin: { left: 14, right: 14 },
  });

  if (input.gaps.length) {
    // @ts-expect-error jspdf-autotable adds lastAutoTable
    y = (doc.lastAutoTable?.finalY ?? y + 40) + 10;
    if (y > 240) {
      doc.addPage();
      y = 20;
    }
    doc.setTextColor(...NAVY);
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("Gap analysis against Workforce Data", 14, y);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(20, 20, 20);
    doc.setFontSize(9);
    let gy = y + 6;
    for (const g of input.gaps) {
      const lines = doc.splitTextToSize(`• ${g}`, W - 28) as string[];
      if (gy + lines.length * 4.5 > 282) {
        doc.addPage();
        gy = 20;
      }
      doc.text(lines, 14, gy);
      gy += lines.length * 4.5 + 1.5;
    }
  }

  doc.setTextColor(...GREY);
  doc.setFontSize(8);
  doc.text("Generated by DDHS Equity Intelligence. Figures sync from your latest Workforce Data upload.", 14, 290);

  doc.save(`EEA13-goals-${new Date().toISOString().slice(0, 10)}.pdf`);
}
